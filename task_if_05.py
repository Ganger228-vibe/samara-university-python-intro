# Задание 5. Условный оператор
# Условие: Даны три целых числа.
# Найти количество положительных и количество отрицательных чисел в исходном наборе.

def main():
    print("=== Задание 5 (Условный оператор). Подсчет положительных и отрицательных чисел ===")
    a = int(input("Введите первое целое число: "))
    b = int(input("Введите второе целое число: "))
    c = int(input("Введите третье целое число: "))
    
    # Инициализация счетчиков
    positive_count = 0
    negative_count = 0
    
    # Проверка первого числа
    if a > 0:
        positive_count += 1
    elif a < 0:
        negative_count += 1
        
    # Проверка второго числа
    if b > 0:
        positive_count += 1
    elif b < 0:
        negative_count += 1
        
    # Проверка третьего числа
    if c > 0:
        positive_count += 1
    elif c < 0:
        negative_count += 1
        
    print(f"Количество положительных чисел: {positive_count}")
    print(f"Количество отрицательных чисел: {negative_count}")

if __name__ == "__main__":
    main()
