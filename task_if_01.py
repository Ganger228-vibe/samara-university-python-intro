# Задание 1. Условный оператор
# Условие: Дано целое число. Если оно является положительным, то прибавить к нему 1;
# в противном случае не изменять его. Вывести полученное число.

def main():
    print("=== Задание 1 (Условный оператор). Модификация положительного числа ===")
    n = int(input("Введите целое число: "))
    
    # Если число положительное (больше нуля), прибавляем 1
    if n > 0:
        n += 1
    
    print(f"Полученное число: {n}")

if __name__ == "__main__":
    main()
