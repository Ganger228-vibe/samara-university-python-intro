# Задание 2. Ввод и вывод данных, оператор присваивания
# Условие: Дана сторона квадрата a. Найти его площадь S = a^2.
# Все входные и выходные данные являются вещественными числами.

def main():
    print("=== Задание 2. Площадь квадрата ===")
    a = float(input("Введите сторону квадрата a: "))
    
    # Вычисление площади по формуле S = a^2
    area = a ** 2
    
    print(f"Площадь квадрата S = {area}")

if __name__ == "__main__":
    main()
