# Задание 7. Ввод и вывод данных, оператор присваивания
# Условие: Найти длину окружности L и площадь круга S заданного радиуса R:
# L = 2 * pi * R, S = pi * R^2.
# В качестве значения pi использовать 3.14.
# Все входные и выходные данные являются вещественными числами.

PI = 3.14

def main():
    print("=== Задание 7. Длина окружности и площадь круга ===")
    r = float(input("Введите радиус круга R: "))
    
    # Вычисление длины окружности и площади круга
    length = 2.0 * PI * r
    area = PI * (r ** 2)
    
    print(f"Длина окружности L = {length}")
    print(f"Площадь круга S = {area}")

if __name__ == "__main__":
    main()
