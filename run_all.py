def main():
    while True:
        print("\n" + "=" * 50)
        print(" МЕНЮ ВЫБОРА ЗАДАНИЯ ДЛЯ ТЕСТИРОВАНИЯ")
        print("=" * 50)
        print("Раздел 1: Ввод и вывод данных (1-10)")
