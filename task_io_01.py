# Задание 1. Ввод и вывод данных, оператор присваивания
# Условие: Дана сторона квадрата a. Найти его периметр P = 4 * a.
# Все входные и выходные данные являются вещественными числами.

def main():
    print("=== Задание 1. Периметр квадрата ===")
    a = float(input("Введите сторону квадрата a: "))
    
    # Вычисление периметра по формуле P = 4 * a
    perimeter = 4.0 * a
    
    print(f"Периметр квадрата P = {perimeter}")

if __name__ == "__main__":
    main()
