# Задание 4. Ввод и вывод данных, оператор присваивания
# Условие: Дан диаметр окружности d. Найти ее длину L = pi * d.
# В качестве значения pi использовать 3.14.
# Все входные и выходные данные являются вещественными числами.

PI = 3.14

def main():
    print("=== Задание 4. Длина окружности по диаметру ===")
    d = float(input("Введите диаметр окружности d: "))
    
    # Вычисление длины окружности L = pi * d
    length = PI * d
    
    print(f"Длина окружности L = {length}")

if __name__ == "__main__":
    main()
