"""
Лаунчер для проверки заданий io1 - io10 и if1 - if5
"""
TASKS = {
    "1": ("io1", "Периметр квадрата"),
    "2": ("io2", "Площадь квадрата"),
    "3": ("io3", "Площадь и периметр прямоугольника"),
    "4": ("io4", "Длина окружности по диаметру"),
    "5": ("io5", "Объем и площадь поверхности куба"),
    "6": ("io6", "Объем и площадь поверхности параллелепипеда"),
    "7": ("io7", "Длина окружности и площадь круга по радиусу"),
    "8": ("io8", "Среднее арифметическое двух чисел"),
    "9": ("io9", "Среднее геометрическое двух чисел"),
    "10": ("io10", "Операции над квадратами ненулевых чисел"),
    "11": ("if1", "Модификация положительного числа"),
    "12": ("if2", "Двухвариантное изменение числа"),
    "13": ("if3", "Трёхвариантное ветвление"),
    "14": ("if4", "Подсчет положительных чисел"),
    "15": ("if5", "Подсчет положительных и отрицательных"),
}

def main():
    while True:
        print("\n" + "=" * 50)
        print(" МЕНЮ ТЕСТИРОВАНИЯ ЗАДАНИЙ")
        print("=" * 50)
        print("Раздел 1: Ввод и вывод данных (1-10)")
        for i in range(1, 11):
            key = str(i)
            print(f" [{key:>2}] {TASKS[key][0]}.py - {TASKS[key][1]}")
        print("-" * 50)
        print("Раздел 2: Условный оператор (11-15)")
        for i in range(11, 16):
            key = str(i)
            print(f" [{key:>2}] {TASKS[key][0]}.py - {TASKS[key][1]}")
        print("-" * 50)
        print(" [ 0] Выход")
        print("=" * 50)
        
        choice = input("Выберите номер задания: ").strip()
        if choice == "0":
            break
        elif choice in TASKS:
            mod_name, desc = TASKS[choice]
            print(f"\nЗапуск {mod_name}.py ({desc}):\n" + "-" * 40)
            try:
                with open(f"{mod_name}.py", "r", encoding="utf-8") as f:
                    code = f.read()
                exec(code, {})
            except Exception as e:
                print(f"Ошибка: {e}")
        else:
            print("Неверный номер.")

if __name__ == "__main__":
    main()
