# Задание 3. Ввод и вывод данных, оператор присваивания
# Условие: Даны стороны прямоугольника a и b. Найти его площадь S = a * b и периметр P = 2 * (a + b).
# Все входные и выходные данные являются вещественными числами.

def main():
    print("=== Задание 3. Площадь и периметр прямоугольника ===")
    a = float(input("Введите сторону прямоугольника a: "))
    b = float(input("Введите сторону прямоугольника b: "))
    
    # Вычисление площади и периметра
    area = a * b
    perimeter = 2.0 * (a + b)
    
    print(f"Площадь прямоугольника S = {area}")
    print(f"Периметр прямоугольника P = {perimeter}")

if __name__ == "__main__":
    main()
